<h3 class="general-header">3. SKATEBOARD</h3>

<ol type="1">
<li><b>Organization of participants</b><br>
Each group of five participants has 30 minutes to "go on stage". Out of these minutes, half is for non-scoring warm-ups and the other 15 minutes are for the scored competition.</li>
<li><b>One participant at a time</b><br>
During the competition, only one participant may skate at a time. The next skater can begin if a trick fails or if the participant does more tricks than allowed.</li>
<li><b>Skateboarding rules: scoring system</b><br>
The judges have to rate the skaters during their performance. The score will range from 0-100 points, and the final score will be an average of what the judge’s rate, as long as there are three judges. If there are five, the highest or lowest score isn’t taken into account, and they average the three middle scores.</li>
<li><b>Skater safety</b><br>
Each skater must use a skateboard endorsed by the federation and they must wear safety equipment. In fact, helmets are mandatory for skaters under 18 years of age.<br>
Also, in order to identify each skater, vests, numbers, or name tags must be worn. Official jerseys are only for World Skate competitions.</li>
<li><b>Skateboarding rules: competition rounds</b><br>
In the skatepark discipline, the three rounds are qualifying, preliminaries/semifinals, and finals. Then, each one competes for between 40 and 60 seconds.<br>
In the street discipline, there are also three rounds: qualifying, preliminary/semifinals and finals. In the beginning, skaters compete in turns of up to seven participants.</li>
<li><b>Timekeeper</b><br>
The role of a timekeeper is fundamental in competitions. That’s why you also have to talk about it when going over the main skateboarding rules. The clock starts when the skater places both feet on the board, starting his turn. For all rounds, they have five seconds to settle in before starting.</li>
</ol>

